#!/usr/bin/env python3
"""
Convert a picture into the C file used for the nice!view boot image.

    python3 tools/make_boot_image.py my_picture.png            # -> src/boot_image_data.c
    python3 tools/make_boot_image.py my_picture.png --invert   # swap black / white
    python3 tools/make_boot_image.py my_picture.png --dither   # photo-like pictures

The picture is fitted into 160 x 68 pixels (black bars are added if the aspect ratio
differs) and converted to 1 bit per pixel in the LVGL "indexed 1 bit" format
(8 bytes palette + 20 bytes per row x 68 rows).

Needs Pillow:  pip install pillow
"""
import argparse
import sys

from PIL import Image, ImageOps

W, H = 160, 68


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("image", help="input picture (png, jpg, bmp, ...)")
    ap.add_argument("-o", "--output", default="src/boot_image_data.c", help="output C file")
    ap.add_argument("--threshold", type=int, default=128,
                    help="0..255, pixels brighter than this become white (default 128)")
    ap.add_argument("--dither", action="store_true", help="dither instead of a hard threshold")
    ap.add_argument("--invert", action="store_true", help="swap black and white")
    ap.add_argument("--fit", choices=["contain", "cover", "stretch"], default="contain",
                    help="contain: keep the aspect ratio, add bars (default)\n"
                         "cover: keep the aspect ratio, crop\n"
                         "stretch: distort to 160 x 68")
    ap.add_argument("--preview", help="also write a PNG preview of the result")
    args = ap.parse_args()

    img = Image.open(args.image).convert("RGBA")
    # transparent pixels -> black
    bg = Image.new("RGBA", img.size, (0, 0, 0, 255))
    img = Image.alpha_composite(bg, img).convert("L")

    if args.fit == "stretch":
        img = img.resize((W, H), Image.LANCZOS)
    elif args.fit == "cover":
        img = ImageOps.fit(img, (W, H), Image.LANCZOS)
    else:
        img = ImageOps.pad(img, (W, H), Image.LANCZOS, color=0)

    if args.dither:
        bw = img.convert("1")  # Floyd-Steinberg
    else:
        bw = img.point(lambda p: 255 if p > args.threshold else 0).convert("1")
    if args.invert:
        bw = ImageOps.invert(bw.convert("L")).convert("1")

    if args.preview:
        bw.convert("L").save(args.preview)

    px = bw.load()
    stride = (W + 7) // 8
    data = bytearray()
    for y in range(H):
        for xb in range(stride):
            byte = 0
            for bit in range(8):
                x = xb * 8 + bit
                v = 1 if (x < W and px[x, y] != 0) else 0   # 1 = white
                byte |= v << (7 - bit)
            data.append(byte)

    # palette: index 0 = black, index 1 = white  (B, G, R, A)
    palette = bytes([0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF])
    blob = palette + bytes(data)

    lines = []
    for i in range(0, len(blob), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 12]) + ",")

    with open(args.output, "w") as f:
        f.write("/* Generated by tools/make_boot_image.py - do not edit by hand. */\n")
        f.write("#include <lvgl.h>\n\n")
        f.write("static const uint8_t swanboard_boot_image_map[] = {\n")
        f.write("\n".join(lines) + "\n};\n\n")
        f.write("const lv_img_dsc_t swanboard_boot_image = {\n")
        f.write("    .header.cf = LV_IMG_CF_INDEXED_1BIT,\n")
        f.write("    .header.always_zero = 0,\n")
        f.write("    .header.reserved = 0,\n")
        f.write(f"    .header.w = {W},\n")
        f.write(f"    .header.h = {H},\n")
        f.write(f"    .data_size = {len(blob)},\n")
        f.write("    .data = swanboard_boot_image_map,\n")
        f.write("};\n")
    print(f"wrote {args.output} ({len(blob)} bytes of image data)", file=sys.stderr)


if __name__ == "__main__":
    main()
